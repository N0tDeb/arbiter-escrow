import { artifacts, ethers } from "hardhat";
import * as fs from "fs";
import * as path from "path";

const DELIVERY_DURATION_SECONDS = 24 * 60 * 60;

async function writeFrontendContractConfig(address: string) {
  const artifact = await artifacts.readArtifact("Escrow");
  const configPath = path.resolve(
    __dirname,
    "..",
    "web",
    "src",
    "config",
    "escrow-contract.ts"
  );

  const generated = `// Generated by scripts/deploy.ts. Do not edit manually.\nexport const ESCROW_ADDRESS = "${address}" as const;\n\nexport const ESCROW_ABI = ${JSON.stringify(
    artifact.abi,
    null,
    2
  )} as const;\n`;

  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, generated, "utf8");

  console.log(`Updated frontend contract config: ${path.relative(process.cwd(), configPath)}`);
}

async function main() {
  const [buyer, seller, arbitrator] = await ethers.getSigners();

  console.log("Deploying Arbiter escrow contract...");
  console.log(`Buyer:      ${buyer.address}`);
  console.log(`Seller:     ${seller.address}`);
  console.log(`Arbitrator: ${arbitrator.address}`);

  const Escrow = await ethers.getContractFactory("Escrow", buyer);
  const escrow = await Escrow.deploy(
    seller.address,
    arbitrator.address,
    DELIVERY_DURATION_SECONDS
  );

  await escrow.waitForDeployment();
  const address = await escrow.getAddress();

  console.log(`Escrow deployed to: ${address}`);
  await writeFrontendContractConfig(address);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
